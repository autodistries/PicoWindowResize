// Conservative accessor contracts preserve the observed AArch64 HFA return ABI.
// Ignore relocated PC-relative branch/page addresses; retain all other instructions.
inline uint32_t abiInstruction(uint32_t word){
    if((word&0x7c000000)==0x14000000)return word&0xfc000000;
    if((word&0x9f000000)==0x90000000)return word&0x9f00001f;
    return word;
}
template<size_t N> inline bool accessorContract(const uint32_t* code,const uint32_t (&expected)[N]){
    for(size_t i=0;i<N;i++)if(abiInstruction(code[i])!=expected[i])return false;
    return true;
}
